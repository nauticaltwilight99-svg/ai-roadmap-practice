import numpy as np

# === ВХОДНЫЕ ДАННЫЕ ===
# Три признака: уши, хвост, шерсть
# 1 — сильно выражено, 0 — отсутствует
inputs = np.array([0.1, 0.9, 0.2])  # пример: кошка

# === ВЕСА ДЛЯ ДВУХ НЕЙРОНОВ ===
# Каждый нейрон имеет свои веса
# Первый — "распознаёт кошку"
# Второй — "распознаёт собаку"
weights = np.array([
    [0.7, -0.3, 0.6],  # нейрон 1 — кошка
    [-0.5, 0.8, 0.3]   # нейрон 2 — собака
])

# === СМЕЩЕНИЯ (bias) ===
biases = np.array([0.1, 0.2])

# === РАСЧЁТ ===
# np.dot умножает матрицу входов на веса
outputs = np.dot(weights, inputs) + biases

print("Входные данные:", inputs)
print("Весовые коэффициенты (нейрон 1 и 2):")
print(weights)
print("Смещения:", biases)
print("\nРезультаты работы нейронов:")
print("Нейрон 1 (кошка 🐱):", outputs[0])
print("Нейрон 2 (собака 🐶):", outputs[1])

# === КТО ПОБЕДИЛ ===
if outputs[0] > outputs[1]:
    print("\n→ Модель думает: это КОШКА 🐱")
else:
    print("\n→ Модель думает: это СОБАКА 🐶")
