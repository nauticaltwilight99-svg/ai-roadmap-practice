import numpy as np

# создаём массив из 5 элементов
arr = np.array([2, 4, 6, 8, 10])
print("Исходный массив:", arr)

# 1️⃣ прибавляем 5 к каждому элементу
print("Прибавляем 5:", arr + 5)

# 2️⃣ умножаем на 3
print("Умножаем на 3:", arr * 3)

# 3️⃣ создаём второй массив
arr2 = np.array([1, 1, 1, 1, 1])
print("Второй массив:", arr2)

# 4️⃣ складываем два массива
print("Сумма двух массивов:", arr + arr2)
