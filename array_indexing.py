import numpy as np

arr = np.array([10, 20, 30, 40, 50])
print("Исходный массив:", arr)

# 1️⃣ Получаем элемент по индексу
print("Первый элемент:", arr[0])
print("Последний элемент:", arr[-1])

# 2️⃣ Берём срез (часть массива)
print("Первые три элемента:", arr[0:3])
print("Середина массива:", arr[1:4])

# 3️⃣ Берём каждый второй элемент
print("Каждый второй элемент:", arr[::2])