import numpy as np

arr = np.array([1, 2, 3, 4, 5])

# Сложение числа с массивом
print("arr + 10:", arr + 10)

# Умножение массива на число
print("arr * 2:", arr * 2)

# Создаём второй массив для сложения
arr2 = np.array([10, 20, 30, 40, 50])
print("arr + arr2:", arr + arr2)

# Деление массива на число
print("arr / 2:", arr / 2)
