import numpy as np

# === ВХОДНЫЕ ДАННЫЕ ===
# Представим, что у нас есть изображение с 3 признаками:
# 1 — уши, 2 — хвост, 3 — шерсть
# Это не пиксели, а просто условные значения
inputs = np.array([0.1, 0.9, 0.2])

# === ВЕСА (настройки модели) ===
# Нейрон сам "учится" менять веса во время обучения
weights = np.array([0.7, -0.3, 0.6])

# === СМЕЩЕНИЕ (bias) ===
# Это как "предвзятость" — помогает нейрону подстраиваться
bias = 0.1

# === ВЫЧИСЛЕНИЕ РЕЗУЛЬТАТА ===
# Математически: выход = сумма(вход * вес) + смещение
output = np.dot(inputs, weights) + bias

print("Входные данные:", inputs)
print("Веса:", weights)
print("Смещение:", bias)
print("Результат работы нейрона:", output)
